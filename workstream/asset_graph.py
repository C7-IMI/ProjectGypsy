#!/usr/bin/env python3
"""Deterministic asset dependency graph and byte-budget validator for Gypsy Studio.

This module builds a read-only graph over the assets that workstream/assets.py already
scanned, using an explicit sidecar for the edges. It never guesses an edge: an edge that is
not declared in the sidecar does not exist in the graph, and a sidecar that is missing or
malformed is reported rather than filled in.

Sidecar schema gypsy.asset-dependencies/v1
------------------------------------------
assets/registry/dependencies.json by default (override with the dependencies argument or the
--dependencies flag):

    {
      "schema": "gypsy.asset-dependencies/v1",
      "nodes": [
        {"path": "assets/hero/wayfarer.glb", "role": "base", "basis": "generated by ..."},
        {"path": "assets/hero/wayfarer_lod1.glb", "role": "lod", "basis": "..."}
      ],
      "edges": [
        {"from": "assets/hero/wayfarer.glb", "to": "assets/hero/wayfarer_lod1.glb",
         "kind": "derived", "basis": "assets/hero/wayfarer_lods.json records ..."}
      ],
      "budgets": {"model": 8388608}
    }

Direction is fixed and documented: from -> to means "to is produced from / depends on from".
from is the dependency; to is the dependent. roots are nodes with no incoming edge (nothing
they depend on); leaves are nodes with no outgoing edge (nothing depends on them); isolated
nodes are both. layers are dependency depths: layer 0 has no declared dependency, layer 1
depends only on layer 0, and so on.

Rules
-----
* Only explicitly declared edges exist. The real sidecar declares the Wayfarer LOD1/LOD2/FBX
  edges and nothing else; Godot import copies under game/assets/ are not declared because no
  copy/import edge is recorded for them.
* Node declarations are optional metadata ("role", "basis"). A declared node that is not in the
  scanned registry is an unknown-node error; an edge endpoint that is not in the registry is a
  missing-node error; a self-edge is an error; a cycle is an error (the members are reported and
  left unlayered).
* Duplicate node declarations and duplicate edges are warnings, not errors; the first declaration
  wins and the duplicate is ignored.
* A missing sidecar is a warning and an empty edge set, not a fabricated graph. A present but
  malformed sidecar is an error, because a file that exists and cannot be read leaves the graph
  incomplete.
* Per-media-kind byte budgets come from the sidecar "budgets" object and/or the --budget flag
  (the flag wins). When no budget is configured the status is "not-configured" with a warning and
  no failure: an unmeasured budget is not a pass. A configured and exceeded budget is a finding
  and fails --validate.
* The payload is gypsy.asset-graph/v1, JSON-safe by construction, with validate_graph, to_json
  and an atomic state file (workstream/state/asset-graph.json, gitignored) for comparison only.

Limits
------
Read-only: no importer dependency inference, no engine output graph, no per-file budgets, no
legal clearance. The graph is only as complete as the declared sidecar; the registry's
duplicate-content groups are not dependency edges.

Wiring: workstream/gypsy.py and the dashboard are not modified here (the Lead owns integration).
The module has a standalone entry point.

Public API
----------
    SCHEMA, DEPENDENCY_SCHEMA, EDGE_KINDS, DEFAULT_DEPENDENCIES, DEFAULT_STATE, AssetGraphError
    load_dependencies(path) -> (data, info, errors, warnings)
    build_graph(registry=None, dependencies=None, budgets=None) -> dict
    validate_graph(payload) -> list[str]
    problems(payload) -> list[str]
    to_json(payload, indent=2) -> str
    save_state(payload, path=None) -> Path
    load_state(path=None) -> dict
    render_summary(payload) -> str
    main(argv=None) -> int

Usage:
    python workstream/asset_graph.py [--dependencies PATH] [--budget MEDIA=BYTES ...] [--json]
    python workstream/asset_graph.py --validate [--json]
    python workstream/asset_graph.py --save-state [PATH]
    python workstream/asset_graph.py --state PATH [--json]
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

import assets
import gypsy

SCHEMA = "gypsy.asset-graph/v1"
DEPENDENCY_SCHEMA = "gypsy.asset-dependencies/v1"
EDGE_KINDS = ("derived", "export", "reference")
DEFAULT_DEPENDENCIES = gypsy.REPO_ROOT / "assets" / "registry" / "dependencies.json"
DEFAULT_STATE = gypsy.STATE_DIR / "assets" / "graph.json"
BUDGET_PATTERN = re.compile(r"^([A-Za-z]+)=([0-9]+)$")


class AssetGraphError(ValueError):
    """A dependency sidecar, graph payload or state file is unreadable or invalid."""


def _posix(value: str) -> str:
    return value.replace("\\", "/")


def _path_label(path: Path) -> str:
    try:
        return path.resolve().relative_to(gypsy.REPO_ROOT).as_posix()
    except (OSError, ValueError):
        return _posix(str(path.resolve() if path.is_absolute() else path))


def _utc_now() -> str:
    return gypsy.now_iso()


def load_dependencies(path=None):
    """Load the dependency sidecar.

    Returns (data, info, errors, warnings). data is None when the file is missing or cannot be
    trusted; info is the JSON-safe description of what was read. A missing file is a warning.
    """
    source = Path(path).expanduser() if path else DEFAULT_DEPENDENCIES
    info = {
        "path": _path_label(source),
        "found": source.is_file(),
        "loaded": False,
        "schema": None,
        "nodes": 0,
        "edges": 0,
        "warnings": [],
    }
    errors = []
    warnings = []
    if not source.is_file():
        message = "dependency sidecar not found: {}".format(info["path"])
        info["warnings"].append(message)
        warnings.append(message)
        return None, info, errors, warnings
    try:
        text = source.read_text(encoding="utf-8-sig")
    except OSError as exc:
        message = "dependency sidecar is unreadable: {}".format(exc)
        info["warnings"].append(message)
        errors.append(message)
        return None, info, errors, warnings
    try:
        data = json.loads(text)
    except json.JSONDecodeError as exc:
        message = "dependency sidecar is not valid JSON: {}".format(exc)
        info["warnings"].append(message)
        errors.append(message)
        return None, info, errors, warnings
    if not isinstance(data, dict):
        message = "dependency sidecar must be a JSON object"
        info["warnings"].append(message)
        errors.append(message)
        return None, info, errors, warnings
    if data.get("schema") != DEPENDENCY_SCHEMA:
        message = "dependency sidecar schema must be {!r}, found {!r}".format(
            DEPENDENCY_SCHEMA, data.get("schema")
        )
        info["warnings"].append(message)
        errors.append(message)
        return None, info, errors, warnings
    info["schema"] = DEPENDENCY_SCHEMA
    nodes = data.get("nodes", [])
    if nodes is None:
        nodes = []
    if not isinstance(nodes, list):
        message = "dependency sidecar nodes must be a list"
        info["warnings"].append(message)
        errors.append(message)
        return None, info, errors, warnings
    edges = data.get("edges")
    if not isinstance(edges, list):
        message = "dependency sidecar edges must be a list"
        info["warnings"].append(message)
        errors.append(message)
        return None, info, errors, warnings
    info["nodes"] = len(nodes)
    info["edges"] = len(edges)
    info["loaded"] = True
    return data, info, errors, warnings


def _node_record(asset, declared=False, role=None, basis=None) -> dict:
    return {
        "path": asset["path"],
        "media": asset["media"],
        "bytes": asset["bytes"],
        "sha256": asset["sha256"],
        "root": asset.get("root"),
        "declared": declared,
        "role": role,
        "basis": basis,
    }


def _budget_map(raw, warnings) -> dict:
    """Validate an optional sidecar budgets object; invalid entries are warnings."""
    result = {}
    if raw is None:
        return result
    if not isinstance(raw, dict):
        warnings.append("dependency sidecar budgets must be an object; ignored")
        return result
    for media, value in raw.items():
        if media not in assets.MEDIA_KINDS:
            warnings.append(
                "dependency sidecar budget for unknown media kind {!r}; ignored".format(media)
            )
            continue
        if not isinstance(value, int) or isinstance(value, bool) or value <= 0:
            warnings.append(
                "dependency sidecar budget for {!r} must be a positive integer; ignored".format(media)
            )
            continue
        result[media] = value
    return result


def _explicit_budgets(raw) -> dict:
    """Validate caller/CLI budgets strictly; raise AssetGraphError on anything invalid."""
    if not isinstance(raw, dict):
        raise AssetGraphError("budgets must be an object of media kind -> positive integer bytes")
    result = {}
    for media, value in raw.items():
        if media not in assets.MEDIA_KINDS:
            raise AssetGraphError(
                "unknown budget media kind {!r}; choose one of {}".format(
                    media, list(assets.MEDIA_KINDS)
                )
            )
        if not isinstance(value, int) or isinstance(value, bool) or value <= 0:
            raise AssetGraphError(
                "budget for {!r} must be a positive integer number of bytes".format(media)
            )
        result[media] = value
    return result


def _strongly_connected(nodes, edges) -> list:
    """Tarjan SCC; returns groups (sorted lists) with more than one node, sorted."""
    adjacency = {node: [] for node in nodes}
    for edge in edges:
        adjacency[edge["from"]].append(edge["to"])
    for node in nodes:
        adjacency[node].sort()
    index = {}
    lowlink = {}
    stack = []
    on_stack = set()
    groups = []
    counter = [0]

    def visit(node):
        index[node] = counter[0]
        lowlink[node] = counter[0]
        counter[0] += 1
        stack.append(node)
        on_stack.add(node)
        for target in adjacency[node]:
            if target not in index:
                visit(target)
                lowlink[node] = min(lowlink[node], lowlink[target])
            elif target in on_stack:
                lowlink[node] = min(lowlink[node], index[target])
        if lowlink[node] == index[node]:
            group = []
            while True:
                member = stack.pop()
                on_stack.discard(member)
                group.append(member)
                if member == node:
                    break
            if len(group) > 1:
                groups.append(sorted(group))

    for node in sorted(nodes):
        if node not in index:
            visit(node)
    return sorted(groups, key=lambda group: (len(group), group))


def _layer_graph(node_paths, edges):
    """Return (layers, unlayered) using dependency depth; deterministic."""
    dependencies = {path: [] for path in node_paths}
    for edge in edges:
        dependencies[edge["to"]].append(edge["from"])
    decided = {}
    remaining = set(node_paths)
    progress = True
    while progress:
        progress = False
        for node in sorted(remaining):
            needs = dependencies[node]
            if all(need in decided for need in needs):
                decided[node] = 0 if not needs else 1 + max(decided[need] for need in needs)
                remaining.discard(node)
                progress = True
    layers = []
    if decided:
        for level in range(max(decided.values()) + 1):
            layers.append(sorted(path for path, depth in decided.items() if depth == level))
    return layers, sorted(remaining)


def _budget_report(node_paths, nodes, effective, source) -> dict:
    totals = {kind: 0 for kind in assets.MEDIA_KINDS}
    for node in nodes:
        if node["path"] in node_paths:
            totals[node["media"]] += node["bytes"]
    evaluated = []
    findings = []
    if not effective:
        return {
            "configured": False,
            "source": None,
            "totals": totals,
            "evaluated": [],
            "findings": [],
            "status": "not-configured",
        }
    for media in assets.MEDIA_KINDS:
        if media not in effective:
            continue
        budget = effective[media]
        actual = totals[media]
        over_by = max(0, actual - budget)
        status = "exceeded" if over_by else "ok"
        evaluated.append(
            {
                "media": media,
                "budgetBytes": budget,
                "actualBytes": actual,
                "overBy": over_by,
                "status": status,
            }
        )
        if over_by:
            findings.append(
                {
                    "media": media,
                    "budgetBytes": budget,
                    "actualBytes": actual,
                    "overBy": over_by,
                    "message": "{} budget exceeded: {} > {} bytes (over by {})".format(
                        media, actual, budget, over_by
                    ),
                }
            )
    status = "exceeded" if findings else "ok"
    return {
        "configured": True,
        "source": source,
        "totals": totals,
        "evaluated": evaluated,
        "findings": findings,
        "status": status,
    }


def build_graph(registry=None, dependencies=None, budgets=None) -> dict:
    """Build a gypsy.asset-graph/v1 payload from the registry and the explicit sidecar.

    registry: an assets.scan() payload, or None to scan the default roots.
    dependencies: dependency sidecar path, or None for assets/registry/dependencies.json.
    budgets: optional strict media->bytes overrides (CLI/--budget); sidecar budgets are used when
    this is None. Raises AssetGraphError for an invalid registry payload or invalid budgets.
    """
    if registry is None:
        registry = assets.scan()
    elif not isinstance(registry, dict):
        raise AssetGraphError("registry must be an assets.scan() payload object")
    else:
        registry_errors = assets.validate_payload(registry)
        if registry_errors:
            raise AssetGraphError(
                "asset registry payload is not valid: " + "; ".join(registry_errors)
            )

    data, dependency_info, dependency_errors, dependency_warnings = load_dependencies(dependencies)
    errors = list(dependency_errors)
    warnings = list(dependency_warnings)

    assets_by_path = {entry["path"]: entry for entry in registry.get("assets", [])}
    nodes = {path: _node_record(entry) for path, entry in assets_by_path.items()}

    sidecar_budgets = {}
    declared = set()
    edges = []
    skipped = []
    seen_edges = set()

    if isinstance(data, dict):
        raw_nodes = data.get("nodes") or []
        for index, item in enumerate(raw_nodes):
            if not isinstance(item, dict):
                errors.append("dependency sidecar nodes[{}] must be an object".format(index))
                continue
            path = item.get("path")
            if not isinstance(path, str) or not path.strip():
                errors.append("dependency sidecar nodes[{}] has no non-empty path".format(index))
                continue
            path = path.strip().replace("\\", "/")
            if path not in nodes:
                errors.append("unknown node declared in dependency sidecar: " + path)
                continue
            if path in declared:
                warnings.append("dependency sidecar repeats node declaration: " + path)
                continue
            declared.add(path)
            role = item.get("role")
            basis = item.get("basis")
            nodes[path] = _node_record(
                assets_by_path[path],
                declared=True,
                role=role if isinstance(role, str) and role.strip() else None,
                basis=basis if isinstance(basis, str) and basis.strip() else None,
            )

        for index, item in enumerate(data.get("edges") or []):
            label = "dependency sidecar edges[{}]".format(index)
            if not isinstance(item, dict):
                errors.append(label + " must be an object")
                continue
            source_path = item.get("from")
            target_path = item.get("to")
            basis = item.get("basis")
            kind = item.get("kind", "derived")
            missing = []
            if not isinstance(source_path, str) or not source_path.strip():
                missing.append("from")
            if not isinstance(target_path, str) or not target_path.strip():
                missing.append("to")
            if missing:
                errors.append(label + " has no non-empty " + " or ".join(missing))
                continue
            source_path = source_path.strip().replace("\\", "/")
            target_path = target_path.strip().replace("\\", "/")
            if not isinstance(basis, str) or not basis.strip():
                errors.append(label + " has no non-empty basis (a reason is required)")
                continue
            if kind not in EDGE_KINDS:
                errors.append(
                    label + " kind must be one of {}, found {!r}".format(list(EDGE_KINDS), kind)
                )
                continue
            if source_path == target_path:
                errors.append("self-edge declared in dependency sidecar: " + source_path)
                skipped.append({"from": source_path, "to": target_path, "reason": "self-edge"})
                continue
            unknown = [
                endpoint
                for endpoint in (source_path, target_path)
                if endpoint not in nodes
            ]
            if unknown:
                for endpoint in sorted(unknown):
                    errors.append("missing node referenced by dependency edge: " + endpoint)
                skipped.append(
                    {"from": source_path, "to": target_path, "reason": "missing-node"}
                )
                continue
            key = (source_path, target_path)
            if key in seen_edges:
                warnings.append(
                    "dependency sidecar repeats edge {} -> {}; ignored".format(
                        source_path, target_path
                    )
                )
                continue
            seen_edges.add(key)
            edges.append(
                {
                    "from": source_path,
                    "to": target_path,
                    "kind": kind,
                    "basis": basis.strip(),
                }
            )
        budgets_warnings = []
        sidecar_budgets = _budget_map(data.get("budgets"), budgets_warnings)
        dependency_info["warnings"].extend(budgets_warnings)
        warnings.extend(budgets_warnings)

    edges.sort(key=lambda edge: (edge["from"], edge["to"], edge["kind"]))
    node_paths = sorted(nodes)
    cycles = _strongly_connected(node_paths, edges)
    for cycle in cycles:
        errors.append("dependency cycle detected: " + " -> ".join(cycle + [cycle[0]]))
    layers, unlayered = _layer_graph(node_paths, edges)
    roots, leaves = [], []
    for path in node_paths:
        has_incoming = any(edge["to"] == path for edge in edges)
        has_outgoing = any(edge["from"] == path for edge in edges)
        if not has_incoming:
            roots.append(path)
        if not has_outgoing:
            leaves.append(path)

    effective = dict(sidecar_budgets)
    budget_source = "sidecar" if sidecar_budgets else None
    if budgets is not None:
        effective.update(_explicit_budgets(budgets))
        budget_source = "cli"
    if not effective:
        warnings.append("no byte budgets configured; budgets were not assessed")
    budget_report = _budget_report(node_paths, list(nodes.values()), effective, budget_source)

    payload = {
        "schema": SCHEMA,
        "generated": _utc_now(),
        "dependencyFile": dependency_info,
        "registry": {
            "count": len(assets_by_path),
            "totalBytes": registry.get("totalBytes", 0),
            "generated": registry.get("generated"),
        },
        "nodes": [nodes[path] for path in node_paths],
        "edges": edges,
        "roots": roots,
        "leaves": leaves,
        "layers": layers,
        "unlayered": unlayered,
        "cycles": cycles,
        "skippedEdges": sorted(
            skipped, key=lambda item: (item["from"], item["to"], item["reason"])
        ),
        "budgets": budget_report,
        "counts": {
            "assets": len(assets_by_path),
            "nodes": len(node_paths),
            "edges": len(edges),
            "roots": len(roots),
            "leaves": len(leaves),
            "layers": len(layers),
            "cycles": len(cycles),
            "unlayered": len(unlayered),
        },
        "warnings": warnings,
        "errors": errors,
    }
    return payload


def _string_list(value) -> bool:
    return isinstance(value, list) and all(isinstance(item, str) for item in value)


def validate_graph(payload) -> list:
    """Return shape and consistency errors for a graph payload or state file."""
    if not isinstance(payload, dict):
        return ["payload must be a JSON object"]
    errors = []
    if payload.get("schema") != SCHEMA:
        errors.append("schema must be {!r}, found {!r}".format(SCHEMA, payload.get("schema")))
    if not isinstance(payload.get("generated"), str) or not payload["generated"].strip():
        errors.append("generated must be a non-empty string")

    dependency = payload.get("dependencyFile")
    if not isinstance(dependency, dict):
        errors.append("dependencyFile must be an object")
    else:
        if not isinstance(dependency.get("path"), str) or not dependency["path"].strip():
            errors.append("dependencyFile.path must be a non-empty string")
        for field in ("found", "loaded"):
            if not isinstance(dependency.get(field), bool):
                errors.append("dependencyFile.{} must be true or false".format(field))
        schema = dependency.get("schema")
        if schema is not None and not isinstance(schema, str):
            errors.append("dependencyFile.schema must be a string or null")
        for field in ("nodes", "edges"):
            value = dependency.get(field)
            if not isinstance(value, int) or isinstance(value, bool) or value < 0:
                errors.append("dependencyFile.{} must be a non-negative integer".format(field))
        if not _string_list(dependency.get("warnings")):
            errors.append("dependencyFile.warnings must be a list of strings")

    registry = payload.get("registry")
    if not isinstance(registry, dict):
        errors.append("registry must be an object")
    else:
        for field in ("count", "totalBytes"):
            value = registry.get(field)
            if not isinstance(value, int) or isinstance(value, bool) or value < 0:
                errors.append("registry.{} must be a non-negative integer".format(field))
        generated = registry.get("generated")
        if generated is not None and not isinstance(generated, str):
            errors.append("registry.generated must be a string or null")

    nodes = payload.get("nodes")
    if not isinstance(nodes, list):
        errors.append("nodes must be a list")
        nodes = []
    node_paths = []
    for index, node in enumerate(nodes):
        label = "nodes[{}]".format(index)
        if not isinstance(node, dict):
            errors.append("{} must be an object".format(label))
            continue
        path = node.get("path")
        if not isinstance(path, str) or not path.strip():
            errors.append("{}: path must be a non-empty string".format(label))
        else:
            node_paths.append(path)
        if node.get("media") not in assets.MEDIA_KINDS:
            errors.append("{}: media must be one of {}".format(label, list(assets.MEDIA_KINDS)))
        size = node.get("bytes")
        if not isinstance(size, int) or isinstance(size, bool) or size < 0:
            errors.append("{}: bytes must be a non-negative integer".format(label))
        if not isinstance(node.get("sha256"), str) or len(node["sha256"]) != 64:
            errors.append("{}: sha256 must be a 64-character string".format(label))
        root = node.get("root")
        if root is not None and not isinstance(root, str):
            errors.append("{}: root must be a string or null".format(label))
        if not isinstance(node.get("declared"), bool):
            errors.append("{}: declared must be true or false".format(label))
        for field in ("role", "basis"):
            value = node.get(field)
            if value is not None and not isinstance(value, str):
                errors.append("{}: {} must be a string or null".format(label, field))
    if node_paths != sorted(node_paths):
        errors.append("nodes must be sorted by path")
    if len(set(node_paths)) != len(node_paths):
        errors.append("node paths must be unique")
    node_set = set(node_paths)

    edges = payload.get("edges")
    if not isinstance(edges, list):
        errors.append("edges must be a list")
        edges = []
    edge_keys = []
    for index, edge in enumerate(edges):
        label = "edges[{}]".format(index)
        if not isinstance(edge, dict):
            errors.append("{} must be an object".format(label))
            continue
        source = edge.get("from")
        target = edge.get("to")
        if source not in node_set:
            errors.append("{}: from must be a node path".format(label))
        if target not in node_set:
            errors.append("{}: to must be a node path".format(label))
        if source == target:
            errors.append("{}: self-edge is not allowed".format(label))
        if isinstance(source, str) and isinstance(target, str):
            edge_keys.append((source, target))
        if edge.get("kind") not in EDGE_KINDS:
            errors.append("{}: kind must be one of {}".format(label, list(EDGE_KINDS)))
        if not isinstance(edge.get("basis"), str) or not edge["basis"].strip():
            errors.append("{}: basis must be a non-empty string".format(label))
    if edge_keys != sorted(edge_keys):
        errors.append("edges must be sorted by (from, to)")
    if len(set(edge_keys)) != len(edge_keys):
        errors.append("edges must be unique")

    for field in ("roots", "leaves", "unlayered"):
        value = payload.get(field)
        if not _string_list(value) or value != sorted(value):
            errors.append("{} must be a sorted list of strings".format(field))
        elif any(path not in node_set for path in value):
            errors.append("{} must only contain node paths".format(field))
    expected_roots = sorted(
        path
        for path in node_paths
        if not any(edge.get("to") == path for edge in edges if isinstance(edge, dict))
    )
    if _string_list(payload.get("roots")) and sorted(payload["roots"]) != expected_roots:
        errors.append("roots must be the nodes with no incoming edge")
    expected_leaves = sorted(
        path
        for path in node_paths
        if not any(edge.get("from") == path for edge in edges if isinstance(edge, dict))
    )
    if _string_list(payload.get("leaves")) and sorted(payload["leaves"]) != expected_leaves:
        errors.append("leaves must be the nodes with no outgoing edge")

    layers = payload.get("layers")
    if not isinstance(layers, list) or not all(_string_list(layer) for layer in layers):
        errors.append("layers must be a list of lists of strings")
    else:
        layered = []
        for index, layer in enumerate(layers):
            if layer != sorted(layer):
                errors.append("layers[{}] must be sorted".format(index))
            layered.extend(layer)
        if len(set(layered)) != len(layered):
            errors.append("layers must not repeat nodes")
        unlayered = payload.get("unlayered")
        if _string_list(unlayered):
            if sorted(set(layered) | set(unlayered)) != sorted(node_set):
                errors.append("layers and unlayered must partition the nodes")
        depth = {}
        for index, layer in enumerate(layers):
            for path in layer:
                depth[path] = index
        for edge in edges:
            if not isinstance(edge, dict):
                continue
            source, target = edge.get("from"), edge.get("to")
            if source in depth and target in depth and depth[source] >= depth[target]:
                errors.append("layers must place a dependency before its dependent")
                break

    cycles = payload.get("cycles")
    if not isinstance(cycles, list) or not all(_string_list(cycle) for cycle in cycles):
        errors.append("cycles must be a list of lists of strings")
    else:
        for cycle in cycles:
            if len(cycle) < 2:
                errors.append("cycles entries must contain at least two nodes")
            if any(path not in node_set for path in cycle):
                errors.append("cycles must only contain node paths")

    skipped = payload.get("skippedEdges")
    if not isinstance(skipped, list):
        errors.append("skippedEdges must be a list")
    else:
        for index, item in enumerate(skipped):
            label = "skippedEdges[{}]".format(index)
            if not isinstance(item, dict):
                errors.append("{} must be an object".format(label))
                continue
            for field in ("from", "to", "reason"):
                if not isinstance(item.get(field), str) or not item[field].strip():
                    errors.append("{}: {} must be a non-empty string".format(label, field))

    budgets = payload.get("budgets")
    if not isinstance(budgets, dict):
        errors.append("budgets must be an object")
    else:
        if not isinstance(budgets.get("configured"), bool):
            errors.append("budgets.configured must be true or false")
        source = budgets.get("source")
        if source is not None and source not in ("sidecar", "cli"):
            errors.append("budgets.source must be sidecar, cli or null")
        totals = budgets.get("totals")
        if not isinstance(totals, dict) or any(
            not isinstance(totals.get(kind), int)
            or isinstance(totals.get(kind), bool)
            or totals.get(kind, -1) < 0
            for kind in assets.MEDIA_KINDS
        ):
            errors.append("budgets.totals must map every media kind to bytes")
        if budgets.get("status") not in ("not-configured", "ok", "exceeded"):
            errors.append("budgets.status is invalid")
        if not isinstance(budgets.get("evaluated"), list):
            errors.append("budgets.evaluated must be a list")
        else:
            for index, item in enumerate(budgets["evaluated"]):
                label = "budgets.evaluated[{}]".format(index)
                if not isinstance(item, dict):
                    errors.append(label + " must be an object")
                    continue
                if item.get("media") not in assets.MEDIA_KINDS:
                    errors.append(label + ": media is invalid")
                for field in ("budgetBytes", "actualBytes", "overBy"):
                    value = item.get(field)
                    if not isinstance(value, int) or isinstance(value, bool) or value < 0:
                        errors.append("{}: {} must be a non-negative integer".format(label, field))
                if item.get("status") not in ("ok", "exceeded"):
                    errors.append(label + ": status is invalid")
        findings = budgets.get("findings")
        if not isinstance(findings, list):
            errors.append("budgets.findings must be a list")
        else:
            for index, item in enumerate(findings):
                label = "budgets.findings[{}]".format(index)
                if not isinstance(item, dict):
                    errors.append(label + " must be an object")
                    continue
                for field in ("budgetBytes", "actualBytes", "overBy"):
                    value = item.get(field)
                    if not isinstance(value, int) or isinstance(value, bool) or value < 0:
                        errors.append("{}: {} must be a non-negative integer".format(label, field))
                if not isinstance(item.get("message"), str) or not item["message"].strip():
                    errors.append(label + ": message must be a non-empty string")
        if isinstance(budgets.get("evaluated"), list):
            evaluated = budgets["evaluated"]
            status = budgets.get("status")
            expected = "not-configured" if not evaluated else (
                "exceeded" if any(isinstance(item, dict) and item.get("status") == "exceeded" for item in evaluated) else "ok"
            )
            if status != expected:
                errors.append("budgets.status must match the evaluated budgets")
            if bool(evaluated) != bool(budgets.get("configured")):
                errors.append("budgets.configured must match whether budgets were evaluated")
            if bool(findings) != (expected == "exceeded"):
                errors.append("budgets.findings must match the exceeded evaluations")

    counts = payload.get("counts")
    if not isinstance(counts, dict):
        errors.append("counts must be an object")
    else:
        expected = {
            "assets": registry.get("count", 0) if isinstance(registry, dict) else 0,
            "nodes": len(node_paths),
            "edges": len(edges),
            "roots": len(payload.get("roots") or []) if isinstance(payload.get("roots"), list) else 0,
            "leaves": len(payload.get("leaves") or []) if isinstance(payload.get("leaves"), list) else 0,
            "layers": len(layers) if isinstance(layers, list) else 0,
            "cycles": len(cycles) if isinstance(cycles, list) else 0,
            "unlayered": len(payload.get("unlayered") or []) if isinstance(payload.get("unlayered"), list) else 0,
        }
        if counts != expected:
            errors.append("counts must match the graph")

    for field in ("warnings", "errors"):
        if not _string_list(payload.get(field)):
            errors.append("{} must be a list of strings".format(field))
    return errors


def problems(payload) -> list:
    """Return the problems --validate should fail on: graph errors and exceeded budgets."""
    result = list(payload.get("errors") or [])
    budgets = payload.get("budgets") or {}
    for finding in budgets.get("findings") or []:
        result.append(finding.get("message", "budget exceeded"))
    return result


def to_json(payload, indent: int = 2) -> str:
    """Return the graph payload as JSON text after validating it and proving it round-trips."""
    errors = validate_graph(payload)
    if errors:
        raise AssetGraphError("asset graph payload is not valid: " + "; ".join(errors))
    try:
        text = json.dumps(payload, indent=indent, ensure_ascii=False)
        if json.loads(text) != payload:
            raise AssetGraphError("asset graph payload is not JSON-safe: it changed through JSON")
    except (TypeError, ValueError) as exc:
        raise AssetGraphError("asset graph payload is not JSON-safe: {}".format(exc)) from exc
    return text + "\n"


def save_state(payload, path=None) -> Path:
    """Write a validated graph payload to the state file atomically; return the path."""
    target = Path(path) if path else DEFAULT_STATE
    text = to_json(payload)
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_name(target.name + ".tmp")
    try:
        temporary.write_text(text, encoding="utf-8")
        os.replace(str(temporary), str(target))
    finally:
        if temporary.exists():
            try:
                temporary.unlink()
            except OSError:
                pass
    return target


def load_state(path=None) -> dict:
    """Read and validate a graph state file; raise AssetGraphError when it cannot be trusted."""
    source = Path(path) if path else DEFAULT_STATE
    try:
        text = source.read_text(encoding="utf-8-sig")
    except OSError as exc:
        raise AssetGraphError("asset graph state is unreadable: {}: {}".format(source, exc)) from exc
    try:
        data = json.loads(text)
    except json.JSONDecodeError as exc:
        raise AssetGraphError(
            "asset graph state is invalid JSON: {}: {}".format(source, exc)
        ) from exc
    if not isinstance(data, dict):
        raise AssetGraphError("asset graph state must be a JSON object: {}".format(source))
    errors = validate_graph(data)
    if errors:
        raise AssetGraphError("asset graph state is not trustworthy: " + "; ".join(errors))
    return data


def render_summary(payload) -> str:
    """Render a compact human-readable summary of the graph."""
    counts = payload.get("counts", {})
    lines = [
        "asset graph: {} node(s), {} declared edge(s), {} layer(s)".format(
            counts.get("nodes", 0), counts.get("edges", 0), len(payload.get("layers", []))
        )
    ]
    lines.append(
        "roots: {}, leaves: {}, unlayered: {}, cycles: {}".format(
            counts.get("roots", 0),
            counts.get("leaves", 0),
            counts.get("unlayered", 0),
            counts.get("cycles", 0),
        )
    )
    dependency = payload.get("dependencyFile", {})
    lines.append(
        "dependency sidecar: {} (found={} loaded={} nodes={} edges={})".format(
            dependency.get("path"),
            dependency.get("found"),
            dependency.get("loaded"),
            dependency.get("nodes"),
            dependency.get("edges"),
        )
    )
    budgets = payload.get("budgets", {})
    lines.append(
        "budgets: {} (source={})".format(
            budgets.get("status"), budgets.get("source") or "-"
        )
    )
    for item in budgets.get("evaluated") or []:
        lines.append(
            "  {}: {} / {} bytes ({})".format(
                item["media"], item["actualBytes"], item["budgetBytes"], item["status"]
            )
        )
    for finding in budgets.get("findings") or []:
        lines.append("  finding: " + finding["message"])
    for skipped in payload.get("skippedEdges") or []:
        lines.append(
            "  skipped edge: {} -> {} ({})".format(
                skipped["from"], skipped["to"], skipped["reason"]
            )
        )
    for warning in (payload.get("warnings") or [])[:10]:
        lines.append("  warning: " + warning)
    for error in (payload.get("errors") or [])[:10]:
        lines.append("  error: " + error)
    return "\n".join(lines)


def _parse_budget_argument(value: str) -> tuple:
    match = BUDGET_PATTERN.match(value.strip())
    if not match:
        raise AssetGraphError(
            "budget must look like MEDIA=BYTES (for example model=8388608), found {!r}".format(
                value
            )
        )
    media = match.group(1)
    if media not in assets.MEDIA_KINDS:
        raise AssetGraphError(
            "unknown budget media kind {!r}; choose one of {}".format(
                media, list(assets.MEDIA_KINDS)
            )
        )
    size = int(match.group(2))
    if size <= 0:
        raise AssetGraphError("budget bytes must be positive")
    return media, size


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        prog="asset_graph",
        description="Deterministic explicit asset dependency graph and per-media byte budgets.",
    )
    parser.add_argument(
        "--dependencies",
        default=None,
        metavar="PATH",
        help="dependency sidecar (default: assets/registry/dependencies.json)",
    )
    parser.add_argument(
        "--budget",
        action="append",
        default=None,
        metavar="MEDIA=BYTES",
        help="per-media-kind byte budget; repeatable and overrides the sidecar",
    )
    parser.add_argument("--json", action="store_true", help="print the graph payload as JSON")
    parser.add_argument(
        "--validate",
        action="store_true",
        help="exit 1 on graph errors or exceeded configured budgets",
    )
    parser.add_argument(
        "--save-state",
        nargs="?",
        const=str(DEFAULT_STATE),
        default=None,
        metavar="PATH",
        help="write the graph to a state file (default: workstream/state/assets/graph.json)",
    )
    parser.add_argument(
        "--state",
        metavar="PATH",
        help="print a previously saved graph state instead of building (validated first)",
    )
    args = parser.parse_args(argv)

    try:
        budgets = None
        if args.budget:
            budgets = {}
            for value in args.budget:
                media, size = _parse_budget_argument(value)
                budgets[media] = size
        if args.state:
            payload = load_state(args.state)
        else:
            payload = build_graph(dependencies=args.dependencies, budgets=budgets)
        saved = save_state(payload, args.save_state) if args.save_state else None
    except AssetGraphError as exc:
        print("asset_graph: FAIL - {}".format(exc), file=sys.stderr)
        return 2

    if args.json:
        print(to_json(payload), end="")
    else:
        print(render_summary(payload))
        if saved:
            print("state written: {}".format(saved))

    issues = list(validate_graph(payload)) + list(problems(payload))
    if args.validate:
        for issue in issues:
            print("FAIL asset_graph - {}".format(issue), file=sys.stderr)
        return 1 if issues else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
